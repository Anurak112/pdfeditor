export const STRINGS: Record<Locale, Dict> = { th, en };

export type StringKey = keyof typeof th;

/** Fills {name} placeholders. Numbers go through Intl so Thai digits stay grouped correctly. */
export function fill(template: string, params?: Record<string, string | number>, locale: Locale = 'th'): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, key) => {
    const v = params[key];
    if (v === undefined) return whole;
    return typeof v === 'number' ? new Intl.NumberFormat(locale === 'th' ? 'th-TH' : 'en-US').format(v) : v;
  });
}
